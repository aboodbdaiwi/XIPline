#!/usr/bin/python
# -*- coding: utf-8 -*-
"""
archive + plot dicom files generated by 2D B0map
9/2025
@author: Rolf Schulte
"""

import sys
import sonofrecon as sor
import subprocess
import datetime
import shutil


# set parameters
what = sor.get_what()
topdir = sor.dir(what)
plt = '[1 30]'               # (1)=visible plotting, (2)=B0map caxis [Hz]

# redirect output to logfile
if len(sys.argv)>6:
  now = datetime.datetime.now()
  fnlog = topdir + 'log/' + now.strftime("%Y%m%d_%H%M%S") + '_plot_2db0map.txt'
  sys.stdout = open(fnlog,'w')

# print help
if sor.print_help(sys.argv):
  if len(sys.argv)>6:
    sys.stdout.close()
  sys.exit(-1)

# get input parameters
(runnum,exam,series,functionname) = sor.function_input(sys.argv)

# define data directory
datadir = sor.datadir(exam,series,what)

# copy B0map dicom files
sor.copy_dicom(exam,series,datadir)

# actual execution of matlab-compiled program
fname = datadir + 'ex' + exam + '_se' + series + '_P%05d' % int(runnum)
cmd = ['plot_2db0map',datadir,'[]',fname,plt]
sor.run(cmd)

# finishing up
print('plot_2db0map.py done')
if len(sys.argv)>6:
  sys.stdout.close()

sys.exit(0)

