function p = findGEFiles(dataFile)
% Locate the header, waveform and matlab_scripter corresponding to the scan.
assert(isfile(dataFile),'GE ScanArchive not found: %s',dataFile);
[folder,base,ext] = fileparts(dataFile);
p.data = dataFile;
p.header = fullfile(folder,[base '.hdr']);
if ~isfile(p.header)
    files = dir(fullfile(folder,'*.hdr'));
    assert(numel(files)==1,'Could not uniquely find GE .hdr for %s',base);
    p.header = fullfile(folder,files(1).name);
end

files = dir(fullfile(folder,'*matlab_scripter*'));
assert(~isempty(files),'No matlab_scripter found next to GE data.');
found = [];
for ii=1:numel(files)
    filename = fullfile(folder,files(ii).name);
    if contains(fileread(filename),[base ext],'IgnoreCase',true)
        found = ii; break;
    end
end
if isempty(found)
    assert(numel(files)==1,'Cannot uniquely match matlab_scripter file.');
    found = 1;
end
p.scripter = fullfile(folder,files(found).name);
txt = fileread(p.scripter);
token = regexp(txt,'recon_grid3d_gx\s*\((.*?)\)\s*;','tokens','once');
assert(~isempty(token),'Could not find recon_grid3d_gx(...) in scripter.');
p.command = strtrim(token{1});
args = splitReconArguments(p.command);
assert(numel(args)>=12,'Expected 12 arguments in recon_grid3d_gx call.');
p.waveformArg = strtrim(args{3});
wave = strrep(strrep(p.waveformArg,'''',''),'\','/');
[~,name,extension] = fileparts(wave);
p.waveformName = [name extension];
p.waveform = fullfile(folder,p.waveformName);
assert(isfile(p.waveform),'GE waveform not found: %s',p.waveform);
p.mtx_reco = parseMatlabValue(args{4});
p.interp_factor = parseMatlabValue(args{5});
p.delay = parseMatlabValue(args{6});
p.lb = parseMatlabValue(args{7});
p.mask_fac = parseMatlabValue(args{9});
p.coco = parseMatlabValue(args{10});
p.plt = parseMatlabValue(args{11});
p.grdwrp = parseMatlabValue(args{12});
end

function args = splitReconArguments(s)
% Split commas outside quotes and square brackets (no eval).
args = {};
last = 1; depth = 0; quoted = false;
for ii=1:numel(s)
    c = s(ii);
    if c==''''
        quoted = ~quoted;
    elseif ~quoted
        if any(c=='[({'), depth=depth+1; end
        if any(c=='])}'), depth=depth-1; end
        if c==',' && depth==0
            args{end+1} = strtrim(s(last:ii-1)); %#ok<AGROW>
            last = ii+1;
        end
    end
end
args{end+1} = strtrim(s(last:end));
end

function vol = orientGXVolume(vol)

% Apply the XIPline GE orientation to the first three spatial dimensions.
% Input is expected to be a 3-D complex/magnitude volume.

vol = squeeze(vol);

if ndims(vol) ~= 3
    error('Expected a 3-D gas-exchange image volume; received size [%s].', ...
        num2str(size(vol)));
end

vol = permute(vol,[2,1,3]);
vol = imrotate(vol,-90);
vol = flip(vol,1);

end


function value = parseMatlabValue(arg)

% Parse numeric/scalar/vector/logical values extracted from the
% matlab_scripter command without using eval.

arg = strtrim(arg);

if isempty(arg) || strcmp(arg,'[]')
    value = [];
    return;
end

if strcmpi(arg,'true')
    value = true;
    return;
elseif strcmpi(arg,'false')
    value = false;
    return;
end

% Scalar numeric
scalarValue = str2double(arg);

if ~isnan(scalarValue)
    value = scalarValue;
    return;
end

% Numeric vector/matrix such as:
% [0 0 0]
% [1 0 1 16]
% [0 1]

if startsWith(arg,'[') && endsWith(arg,']')

    content = strtrim(arg(2:end-1));

    if isempty(content)
        value = [];
        return;
    end

    rows = strsplit(content,';');
    parsedRows = cell(size(rows));

    for rr = 1:numel(rows)

        rowText = strtrim(rows{rr});

        % Allow commas or spaces
        rowText = strrep(rowText,',',' ');

        nums = sscanf(rowText,'%f').';

        if isempty(nums)
            error('Unable to parse reconstruction parameter: %s',arg);
        end

        parsedRows{rr} = nums;

    end

    try
        value = vertcat(parsedRows{:});
    catch
        error('Unable to parse reconstruction matrix/vector: %s',arg);
    end

    return;
end

error('Unsupported reconstruction parameter in matlab_scripter: %s',arg);

end
