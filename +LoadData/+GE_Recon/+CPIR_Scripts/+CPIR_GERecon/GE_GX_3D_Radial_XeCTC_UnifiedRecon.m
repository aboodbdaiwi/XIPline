function GasExchange = GE_GX_3D_Radial_XeCTC_UnifiedRecon(MainInput)
% GE 129Xe XeCTC gas-exchange reconstruction for XIPline.
% ONE entry point; uses recon_grid3d_gx_XIPline.m and existing fidall /
% GasExchangeFunctions utilities. No second high-level recon is needed.
%
% STEPS (look for corresponding %% sections below):
%   1. Native GE images, k-space and appended bonus FIDs
%   2. Fit acquired bonus FID; gas contamination correction
%   3. MRD-style low-resolution gas and dissolved reconstructions
%   4. Spectroscopy QC; 5. k0 decay; 6. RBC oscillation; 7. images/save
%
% Images: UncorrectedVentImage/VentImage = native GE.
%         GasImage/DissolvedImage/CorrDissolvedImage = MRD-style LR.
% The calibration spectrum is NEVER used for gas contamination subtraction.
% Research use: verify orientation, bonus peaks and quantitative values.

if nargin<1 || ~isstruct(MainInput)
    error('MainInput must be the original GE input structure.');
end
if isfield(MainInput,'GE_UseLRImagesAsPrimary') && ...
        ~isempty(MainInput.GE_UseLRImagesAsPrimary) && ...
        ~isequal(MainInput.GE_UseLRImagesAsPrimary,true)
    error(['GE_UseLRImagesAsPrimary=false is incompatible with the MRD ' ...
           'output contract. GasImage/DissolvedImage/CorrDissolvedImage ' ...
           'must be the reconstructed LOW-resolution images.']);
end

%% STEP 1: Read GE data, reconstruct native images and extract bonus FIDs
fprintf('\n========== GE NATIVE + MRD-STYLE GAS EXCHANGE ==========\n');
GasExchange = runNativeGE(MainInput);
assert(GasExchange.GERaw.ncoils==1, ...
    'Unified GE analysis currently supports one receive coil only.');

% MRD uses OvsFactor; GE native's index-based readout extraction does not
% provide a directly equivalent factor. Supply it explicitly (NaN when
% not reliably recoverable), rather than omit the required field or guess.
if ~isfield(GasExchange,'OvsFactor')
    GasExchange.OvsFactor = NaN;
end

% Native helper never applies gas-contamination subtraction using a
% separate calibration spectrum. Choose an imaging-associated bonus fit
% when explicitly supplied; otherwise keep calibration DisFit for analysis
% under the EXACT MRD field name AppendedDissolvedNMRFit.
assert(isfield(GasExchange,'GasContaminationCorrectionApplied') && ...
       ~GasExchange.GasContaminationCorrectionApplied, ...
       'GE native helper unexpectedly applied gas contamination correction.');
assert(isequaln(GasExchange.CorrectedDissKSpace_SS, ...
                GasExchange.DissolvedKSpace_SS), ...
       'GE native helper produced previously corrected dissolved k-space.');
[fitObj,fitSource,hasImagingBonus] = selectGESpectralFit(MainInput,GasExchange);
GasExchange.AppendedDissolvedNMRFit = fitObj;
GasExchange.DissolvedNMRFitSource = fitSource;
GasExchange.ImagingBonusSpectraPresent = hasImagingBonus;
GasExchange.ExtraQC_GasContamPolicy = ...
    'Gas subtraction requires imaging bonus; calibration allowed for analysis only';
if isempty(fitObj)
    if logical(getOption(MainInput,'GE_RequireSpectralFit',true))
        error(['No usable dissolved NMR fit. Supply MainInput.CalFullPath ' ...
            'for calibration fallback, or a true imaging-associated bonus ' ...
            'fit/FID using MainInput.GE_BonusDissolvedNMRFit or ' ...
            'GE_BonusPostDissolvedFID.']);
    end
    warning('No dissolved NMR fit: downstream spectral analysis will be unavailable.');
end
fprintf('Dissolved NMR fit source: %s (imaging bonus=%d)\n',fitSource,hasImagingBonus);

% Keep the images and XIPline fields generated by the native pathway.
GasExchange.GasImageNative = GasExchange.GasImage;
GasExchange.DissolvedImageNative = GasExchange.DissolvedImage;
GasExchange.VentImageNative = GasExchange.VentImage;
GasExchange.UncorrectedVentImageNative = GasExchange.UncorrectedVentImage;
GasExchange.CorrDissolvedImageNative = GasExchange.CorrDissolvedImage;
GasExchange.NativeImageComplex = GasExchange.ImageComplex;
GasExchange.ReconstructionMethod = 'Native GE gridding + MRD-style LR and QC';
GasExchange.ExtraQC = struct();
GasExchange.RBCOscStatus = 'not attempted';
GasExchange.RBCOscError = '';
GasExchange.LRReconStatus = 'not attempted';
GasExchange.LRReconError = '';
GasExchange.FigureFiles = struct();

outdir = getOption(MainInput,'OutputPath','');
if isempty(outdir), outdir = fullfile(fileparts(MainInput.XeFullPath), 'GE_Analysis'); end
if ~exist(outdir,'dir'), mkdir(outdir); end
GasExchange.outputpath = outdir;
GasExchange.ExtraQC.OutputPath = outdir;
GasExchange.ExtraQC.NativeGradwarpSetting = GasExchange.grdwrp;
GasExchange.ExtraQC.AdditionalLRGradwarpApplied = false;
if ~isempty(GasExchange.grdwrp) && any(double(GasExchange.grdwrp(:)) ~= 0)
    warning(['Native GE gradwarp may be applied to the primary images; ' ...
        'extra MRD-style LR/keyhole images do not replicate that distortion correction.']);
end
saveFigures = logical(getOption(MainInput,'GE_SaveFigures',true));
keepFigures = logical(getOption(MainInput,'GE_KeepFiguresOpen',false));

%% STEP 2: Prepare acquired k-space and apply gas-contamination correction
req = {'GasKSpace_SS','DissolvedKSpace_SS','XeTraj_SS'};
for i=1:numel(req)
    if ~isfield(GasExchange,req{i}) || isempty(GasExchange.(req{i}))
        error('Missing GE raw field: %s. Cannot perform additional recon.',req{i});
    end
end
rawGas = double(GasExchange.GasKSpace_SS);
rawDis = double(GasExchange.DissolvedKSpace_SS);
traj = double(GasExchange.XeTraj_SS);
[nRead,nProj] = size(rawGas);
assert(isequal(size(rawDis),size(rawGas)) && isequal(size(traj),[3 nRead nProj]), ...
    'GE raw gas, dissolved, and trajectory dimensions are inconsistent.');
assert(all(isfinite(real(rawGas(:)))) && all(isfinite(imag(rawGas(:)))) && ...
       all(isfinite(real(rawDis(:)))) && all(isfinite(imag(rawDis(:)))) && ...
       all(isfinite(traj(:))),'Non-finite GE k-space or trajectory.');
% CRITICAL: Scott Robertson's sparse_gridding_distance_mex expects
% NORMALIZED trajectory coordinates (roughly [-0.5,+0.5]) and multiplies
% them by the grid size internally. GE waveform units are already scaled.
trajScale = getOption(MainInput,'GE_LRAdditionalTrajScale',1);
assert(isscalar(trajScale) && isfinite(trajScale) && trajScale>0,'Invalid trajectory scale.');
traj = traj * trajScale;
maxCoord = max(abs(traj(:)));
assert(maxCoord <= 0.5+1e-6, ...
    ['UNSAFE trajectory! max |coordinate|=%.3f > 0.5. ' ...
     'Do NOT send voxel-scaled coordinates into the legacy MEX.'],maxCoord);
GasExchange.ExtraQC.MaxNormalizedCoordinate = maxCoord;
GasExchange.ExtraQC.NormalizedTrajectoryRadiusMax = max(sqrt(sum(traj.^2,1)),[],'all');
GasExchange.ExtraQC.Samples = nRead;
GasExchange.ExtraQC.Projections = nProj;
GasExchange.XeTraj_Normalized_SS = traj;
fprintf('GE raw: %d readout samples x %d profiles; max normalized |axis| = %.4f\n', ...
    nRead,nProj,maxCoord);

% Apply gas contamination subtraction ONLY for a genuine bonus spectrum
% from the SAME imaging acquisition. A calibration fallback supplies
% AppendedDissolvedNMRFit for downstream analysis but cannot trigger it.
correctedDis = rawDis;
GasExchange.GasContaminationCorrectionApplied = false;
GasExchange.GasContaminationCorrectionSource = 'none';
if hasImagingBonus
    dwell_s = double(GasExchange.dwell_s);
    freq_jump = double(GasExchange.freq_jump);
    gasFA = getOption(MainInput,'GE_GasFlipAngle_deg',0.5);
    assert(isscalar(dwell_s) && isfinite(dwell_s) && dwell_s>0, ...
        'GE imaging dwell_s is invalid; cannot apply gas correction.');
    assert(isscalar(freq_jump) && isfinite(freq_jump), ...
        'GE frequency jump is invalid; cannot apply gas correction.');
    assert(isscalar(gasFA) && isfinite(gasFA) && abs(cosd(gasFA))>0.1, ...
        'GE_GasFlipAngle_deg is invalid.');
    assert(numel(fitObj.area)>=3 && numel(fitObj.phase)>=3 && ...
        isfinite(fitObj.area(3)) && fitObj.area(3)>=0 && ...
        isfinite(fitObj.phase(3)), ...
        'Bonus spectral gas peak parameters are invalid.');
    correctedDis = GasExchangeFunctions.GasPhaseContaminationRemoval( ...
        rawDis,rawGas,dwell_s,-freq_jump, ...
        fitObj.phase(3),fitObj.area(3),gasFA);
    assert(isequal(size(correctedDis),size(rawDis)) && ...
        all(isfinite(real(correctedDis(:)))) && ...
        all(isfinite(imag(correctedDis(:)))), ...
        'Bonus-derived gas contamination correction returned invalid k-space.');
    GasExchange.GasContaminationCorrectionApplied = true;
    GasExchange.GasContaminationCorrectionSource = 'imaging bonus dissolved spectrum';
    GasExchange.GasContaminationCorrectionStatus = ...
        'applied: imaging bonus spectroscopy';
else
    GasExchange.GasContaminationCorrectionStatus = ...
        'skipped: no imaging bonus (calibration fit retained for analysis)';
end
GasExchange.CorrectedDissKSpace_SS = correctedDis;
GasExchange.ExtraQC_GasContamRelativeKSpaceChange = ...
    norm(correctedDis(:)-rawDis(:))/max(norm(rawDis(:)),eps);

% Native wrapper stores its gas/dissolved raw k-space BEFORE the native
% raw2grid phase-cycling operation. Only apply to added analyses if needed.
applyChop = getOption(MainInput,'GE_ApplyPhaseCycling','auto');
if ischar(applyChop) || isstring(applyChop)
    if strcmpi(char(applyChop),'auto')
        try
            applyChop = logical(LoadData.GE_Recon.fidall.ischop(GasExchange.GERaw.header));
        catch
            applyChop = false;
            warning('Unable to determine GE phase cycling; no additional chop applied.');
        end
    else
        error('GE_ApplyPhaseCycling must be true, false or ''auto''.');
    end
end
applyChop = logical(applyChop);
if applyChop
    % The GE native raw2grid processing flips alternating excitation signs.
    % Keep each stream's relative contrast unchanged.
    rawGas(:,2:2:end) = -rawGas(:,2:2:end);
    rawDis(:,2:2:end) = -rawDis(:,2:2:end);
    correctedDis(:,2:2:end) = -correctedDis(:,2:2:end);
end
GasExchange.ExtraQC.GEPhaseCyclingAppliedToAdditionalAnalyses = applyChop;
% Match the spatial k-space phase modulation in the supplied native GE
% recon_grid3d_gx_XIPline.m (0.5 voxels for even axes, plus +20 on axis 2).
% This ONLY changes the added reconstruction inputs, not stored original
% raw arrays or their physically measured signal dynamics.
applyNativeShift = logical(getOption(MainInput,'GE_ApplyNativeShiftToExtraRecon',true));
nativeShift = getOption(MainInput,'GE_NativeShift_vox',[]);
if isempty(nativeShift)
    mtx = double(GasExchange.GERaw.mtx_reco(1:3));
    nativeShift = 0.5 * double(mod(mtx,2)==0);
    nativeShift(2) = nativeShift(2) + 20;
end
nativeShift = double(nativeShift(:));
assert(numel(nativeShift)==3 && all(isfinite(nativeShift)), ...
    'GE_NativeShift_vox must contain three finite numbers.');
GasExchange.ExtraQC.NativePhaseShiftVox = nativeShift;
GasExchange.ExtraQC.NativePhaseShiftAppliedToExtraImages = applyNativeShift;
if applyNativeShift
    phaseCycles = nativeShift(1)*squeeze(traj(1,:,:)) + ...
                  nativeShift(2)*squeeze(traj(2,:,:)) + ...
                  nativeShift(3)*squeeze(traj(3,:,:));
    phaseFactor = exp(2*pi*1i*phaseCycles);
    rawGasImage = rawGas .* phaseFactor;
    rawDisImage = rawDis .* phaseFactor;
    correctedDisImage = correctedDis .* phaseFactor;
else
    rawGasImage = rawGas;
    rawDisImage = rawDis;
    correctedDisImage = correctedDis;
end
GasExchange.GasKSpace_SS_Prepared = rawGasImage;
GasExchange.DissolvedKSpace_SS_Prepared = rawDisImage;
GasExchange.CorrectedDissKSpace_SS_Prepared = correctedDisImage;

%% STEP 3: MRD-style low-resolution gas and dissolved images
% Original MRD Dissolved_LowResImageRecon.m uses ONLY a Gaussian GRIDDING
% interpolation kernel (sharpness/sigma = 0.1; extent = 6*sigma), 3x
% overgridding, 15 iterative DCF passes, and image deapodization.
% There is NO separate Gaussian weighting of acquired k-space.
% Kernel sigma defaults to the original MRD setting (0.10); no extra
% k-space weighting is applied.
% NOTE: Gridding kernel width is NOT itself an explicit image resolution
% control, especially when image-domain deapodization is enabled.
N = size(GasExchange.UncorrectedVentImageNative,1);
assert(isequal(size(GasExchange.UncorrectedVentImageNative),[N N N]), ...
    'This wrapper requires an isotropic 3D GE image.');
LRN = getOption(MainInput,'GE_LRMatrix',N);
if isempty(LRN), LRN = N; end
assert(isscalar(LRN) && LRN==round(LRN) && LRN>=16 && LRN<=N, ...
    'GE_LRMatrix must be an integer between 16 and native matrix N.');

% GE_LRSigmaFraction was introduced by this wrapper for additional
% Gaussian *k-space filtering*. It was not in the MRD implementation.
% Ignore it for backward compatibility so old MainInput structures work.
if isfield(MainInput,'GE_LRSigmaFraction') && ...
        ~isempty(MainInput.GE_LRSigmaFraction)
    warning(['MainInput.GE_LRSigmaFraction is deprecated and IGNORED. ' ...
             'No additional k-space filtering is applied. Use ' ...
             'GE_LRKernelSharpness to adjust the gridding kernel.']);
end

kw = getOption(MainInput,'GE_LRKernelSharpness',0.10);
extentFactor = getOption(MainInput,'GE_LRKernelExtentFactor',6);
assert(isnumeric(kw) && isscalar(kw) && isfinite(kw) && ...
       kw > 0 && kw <= 0.35, ...
       'GE_LRKernelSharpness must be a finite scalar in (0, 0.35].');
assert(isnumeric(extentFactor) && isscalar(extentFactor) && ...
       isfinite(extentFactor) && extentFactor>=2 && extentFactor<=10, ...
       'GE_LRKernelExtentFactor must be in [2,10].');
kernelExtent = kw * extentFactor;

GasExchange.LRReconSettings = struct( ...
    'Matrix',LRN, 'TargetOutputMatrix',N, ...
    'KSpaceGaussianFilterApplied',false, ...
    'KernelSharpness',kw, 'KernelExtent',kernelExtent, ...
    'KernelExtentFactor',extentFactor, ...
    'OvergridFactor',3, 'DCFIterations',15, ...
    'Deapodize',true);

GasLR = [];
DisLR = [];
CorrDisLR = [];
if logical(getOption(MainInput,'GE_SkipLRRecon',false))
    error(['GE_SkipLRRecon=true conflicts with the required MRD output ' ...
           'contract: GasImage, DissolvedImage, CorrDissolvedImage must ' ...
           'contain LOW-resolution reconstructions.']);
end
fprintf(['\nMRD-style LR: N=%d; Gaussian GRIDDING kernel sigma=%.3f, ' ...
         'extent=%.3f; NO separate k-space filter\n'], ...
         LRN,kw,kernelExtent);
try
        [GasLR,DisLR,CorrDisLR] = lowResThreeStreams( ...
            LRN,rawGasImage,rawDisImage,correctedDisImage,traj,kw,kernelExtent);
        % If LR reconstruction is on a smaller grid, interpolate BOTH real
        % and imaginary components into the native output voxel lattice.
        % if LRN ~= N
        %     GasLR = resizeComplex3D(GasLR,N);
        %     DisLR = resizeComplex3D(DisLR,N);
        %     CorrDisLR = resizeComplex3D(CorrDisLR,N);
        % end
        % The MRD gridding helper applies rot90(flip(vol)) internally,
        % whereas the GE native wrapper applies different orientation ops.
        % Register the discrete orientations by maximizing correlations
        % between low-resolution gas and native GE ventilation magnitude.
        orientIndex = getOption(MainInput,'GE_LROrientationIndex',[]);
        if isempty(orientIndex)
            [orientIndex,orientationScore] = findLRDihedralOrientation( ...
                abs(GasLR),abs(GasExchange.UncorrectedVentImageNative));
        else
            assert(isscalar(orientIndex) && ismember(orientIndex,1:16), ...
                'GE_LROrientationIndex must be 1..16.');
            orientationScore = NaN;
        end
        GasLR = applyOrientation(GasLR,orientIndex);
        DisLR = applyOrientation(DisLR,orientIndex);
        CorrDisLR = applyOrientation(CorrDisLR,orientIndex);
        GasExchange.LRReconSettings.OrientationIndex = orientIndex;
        GasExchange.LRReconSettings.OrientationCorrelation = orientationScore;
        GasExchange.GasImageLR = GasLR;
        GasExchange.DissolvedImageLR = DisLR;
        GasExchange.CorrDissolvedImageLR = CorrDisLR;
        GasExchange.GasImageCombinedLR = double(abs(GasLR));
        GasExchange.DissolvedImageCombinedLR = double(abs(DisLR));
        GasExchange.LRReconStatus = 'completed';

        % REQUIRED MRD output contract: these THREE exact field names
        % denote low-resolution COMPLEX images, never the native GE images.
        % The GE primary high-resolution ventilation stays under
        % UncorrectedVentImage and the bias-corrected VentImage.
        GasExchange.GasImage = GasLR;
        GasExchange.DissolvedImage = DisLR;
        GasExchange.CorrDissolvedImage = CorrDisLR;
        if ~GasExchange.GasContaminationCorrectionApplied
            assert(isequaln(GasExchange.DissolvedImage, ...
                            GasExchange.CorrDissolvedImage), ...
                'Skipped correction must yield identical dissolved LR images.');
        end
        fprintf('LR reconstruction complete, orientation=%d (corr %.3f).\n', ...
            orientIndex,orientationScore);
    catch ME
        GasExchange.LRReconStatus = 'failed';
        GasExchange.LRReconError = getReport(ME,'extended','hyperlinks','off');
        fprintf(2,'GE low-resolution reconstruction failed: %s\n',ME.message);
        % Do NOT return a structure with native images in GasImage,
        % DissolvedImage or CorrDissolvedImage: downstream XIPline
        % uses those exact MRD names for the low-resolution images.
        rethrow(ME);
end
%% STEP 4: Spectroscopy fit and GE calibration QC figures
% Same filename, layout and field name as the original MRD pipeline.
cal = GasExchange.CalResults;
if ~isempty(fitObj)
    try
        [fig,ratio] = figureDissolvedFit(fitObj);
        GasExchange.FigureFiles.DissolvedNMR = saveMRDFigure( ...
            fig,outdir,'DissolvedNMR',saveFigures,keepFigures);
        GasExchange.ExtraQC.SpectralFitRelativeError = ratio;
        GasExchange.ExtraQC.SpectralFitSource = fitSource;
        GasExchange.DissolvedNMR = ifKeptHandle(fig,keepFigures);
    catch ME
        warning('Dissolved spectroscopy figure failed: %s',ME.message);
    end
end
if isstruct(cal) && ~isempty(cal)
    try
        fig = figureCalibration(cal);
        GasExchange.FigureFiles.Calibration = saveQC(fig,outdir,'GE_Calibration',saveFigures,keepFigures);
    catch ME
        warning('GE gas calibration figure failed: %s',ME.message);
    end
end

%% STEP 5: k0 signal dynamics
try
    [fig,k0] = figureK0Decay(GasExchange,rawGas,rawDis,correctedDis,traj);
    GasExchange.K0Decay = k0; % Retain separate numeric k0 QC metrics.
    % Match MRD exactly: SigDynamics.fig, savefig, then close.
    GasExchange.FigureFiles.SigDynamics = saveMRDFigure( ...
        fig,outdir,'SigDynamics',saveFigures,keepFigures);
    % Backward-compatible alias for callers using the earlier GE wrapper.
    GasExchange.FigureFiles.K0Decay = GasExchange.FigureFiles.SigDynamics;
    GasExchange.SigDynamics = ifKeptHandle(fig,keepFigures);
catch ME
    warning('GE k0 decay QC failed: %s',ME.message);
    GasExchange.K0Decay = struct('Error',ME.message);
end

%% STEP 6: RBC oscillation keyhole images
GasExchange.RBC2Bar_struct = [];
GasExchange.RBCOsc_High_Image = [];
GasExchange.RBCOsc_Low_Image = [];
GasExchange.RBCOsc_Normalization = [];
GasExchange.RBCOsc_High_Key = [];
GasExchange.RBCOsc_Low_Key = [];
GasExchange.RBCOsc_Analysis = [];
if logical(getOption(MainInput,'GE_RunRBCOsc',true))
    % Match MRD: RBC oscillation analysis may use the selected spectral
    % RBC/barrier ratio (bonus preferred; calibration fallback). A separate
    % calibration is less temporally representative; record provenance.
    GasExchange.RBCOscSpectralReferenceSource = fitSource;
    if isempty(fitObj)
        GasExchange.RBCOscStatus = 'skipped: dissolved spectral fit unavailable';
    elseif numel(fitObj.area)<2 || ...
            ~isfinite(fitObj.area(2)) || fitObj.area(2)<=0
        GasExchange.RBCOscStatus = 'skipped: invalid spectral RBC/barrier ratio';
    else
        [XeTR,TRsource] = determineXeTR(MainInput,GasExchange);
        GasExchange.XeTR_s = XeTR;
        GasExchange.XeTR_Source = TRsource;
        if ~isfinite(XeTR) || XeTR<=0
            GasExchange.RBCOscStatus = 'skipped: valid XeTR unavailable';
            warning('RBC oscillation skipped: supply MainInput.GE_XeTR_s (seconds).');
        else
            try
                SpecRBCBarrierRatio = fitObj.area(1)/fitObj.area(2);
                if ~hasImagingBonus
                    warning(['GE RBC oscillation keyhole uses CALIBRATION-derived ' ...
                        'RBC/barrier ratio, not imaging-appended spectroscopy. ' ...
                        'Validate physiological interpretation.']);
                end
                if ~isfinite(SpecRBCBarrierRatio) || SpecRBCBarrierRatio<=0
                    error('Invalid spectroscopy RBC/barrier ratio.');
                end
                % The existing MRD oscillation code assumes EVEN number of
                % projections when computing FFT frequency indices.
                % It also requires sufficiently high sampling frequency.
                npRBC = 2*floor(nProj/2);
                if npRBC<100, error('Insufficient profiles for RBC oscillation fitting.'); end
                if 1/XeTR<=16
                    warning('RBC oscillation sampling rate %.2f Hz <= 16 Hz. Review frequency search.',1/XeTR);
                end
                oscGas = rawGasImage(:,1:npRBC);
                oscDis = correctedDisImage(:,1:npRBC);
                oscTraj = traj(:,:,1:npRBC);
                [highKey,lowKey,disNormalized,RBC2Bar,oscFig] = ...
                    GasExchangeFunctions.dissolved_RBC_Osc_Keyhole( ...
                        oscTraj,oscGas,oscDis,XeTR,SpecRBCBarrierRatio);
                GasExchange.RBC2Bar_struct = RBC2Bar;
                GasExchange.RBCOsc_High_Key = highKey;
                GasExchange.RBCOsc_Low_Key = lowKey;
                GasExchange.RBCOsc_Analysis = struct('NProfilesUsed',npRBC, ...
                    'NProfilesOmittedForEvenLength',nProj-npRBC, ...
                    'TR_s',XeTR,'SpectrumRBCBarrier',SpecRBCBarrierRatio);
                GasExchange.FigureFiles.RBCOscWorkflow = saveQC( ...
                    oscFig,outdir,'OscWorkFlow_Fig',saveFigures,keepFigures);

                % Reconstruct keyhole complex images with SAME native-FOV
                % coordinates used for LR; no matrix multiplication!
                % Existing MRD functions remove NaN keyhole samples.
                targetN = getOption(MainInput,'GE_RBCOscMatrix',LRN);
                assert(targetN<=N && targetN>=16 && targetN==round(targetN), ...
                    'Invalid GE_RBCOscMatrix.');
                Rhigh = GasExchangeFunctions.Dissolved_RBCOscImageRecon( ...
                    targetN,highKey,oscTraj,[0 0 0]);
                Rlow = GasExchangeFunctions.Dissolved_RBCOscImageRecon( ...
                    targetN,lowKey,oscTraj,[0 0 0]);
                Rnorm = GasExchangeFunctions.Dissolved_RBCOscImageRecon( ...
                    targetN,disNormalized,oscTraj,[0 0 0]);
                if targetN~=N
                    Rhigh=resizeComplex3D(Rhigh,N);
                    Rlow=resizeComplex3D(Rlow,N);
                    Rnorm=resizeComplex3D(Rnorm,N);
                end
                if isfield(GasExchange.LRReconSettings,'OrientationIndex')
                    oi = GasExchange.LRReconSettings.OrientationIndex;
                else
                    % Use native image for orientation even if LR was skipped.
                    [oi,~] = findLRDihedralOrientation(abs(Rnorm), ...
                        abs(GasExchange.UncorrectedVentImageNative));
                end
                GasExchange.RBCOsc_High_Image = applyOrientation(Rhigh,oi);
                GasExchange.RBCOsc_Low_Image = applyOrientation(Rlow,oi);
                GasExchange.RBCOsc_Normalization = applyOrientation(Rnorm,oi);
                GasExchange.RBCOscStatus = 'completed';
                fig = figureOscillationImages(GasExchange);
                GasExchange.FigureFiles.RBCOscImages = saveQC( ...
                    fig,outdir,'GE_RBCOscImages',saveFigures,keepFigures);
            catch ME
                GasExchange.RBCOscStatus = 'failed';
                GasExchange.RBCOscError = getReport(ME,'extended','hyperlinks','off');
                warning('GE RBC oscillation analysis failed: %s',ME.message);
            end
        end
    end
else
    GasExchange.RBCOscStatus = 'skipped by user';
end

%% STEP 7: Reconstructed image QC, outputs and optional saving
if ~isempty(GasLR)
    try
        fig = figureLRImages(GasExchange);
        GasExchange.FigureFiles.LRImages = saveQC( ...
            fig,outdir,'GE_LowResolutionImages',saveFigures,keepFigures);
    catch ME
        warning('GE LR image QC plot failed: %s',ME.message);
    end
end
% Enforce the EXACT output field names and the expected image roles from
% radial_3D_XeCTC_gx_recon.m before permitting further analysis.
GasExchange.MRDContractQC = validateMRDOutputContract(GasExchange);

% Optional standalone .mat output. v7.3 handles larger reconstructed datasets.
if logical(getOption(MainInput,'GE_SaveMAT',false))
    matPath=fullfile(outdir,'GE_GasExchange_Recon.mat');
    try
        save(matPath,'GasExchange','-v7.3');
        fprintf('Saved GE gas exchange structure: %s\n',matPath);
    catch ME
        warning('Could not save GE reconstruction MAT: %s',ME.message);
    end
end
fprintf('\nGas contamination: %s\n', GasExchange.GasContaminationCorrectionStatus);
fprintf('Native GE retained. LR: %s | RBC oscillation: %s\n', ...
    GasExchange.LRReconStatus,GasExchange.RBCOscStatus);
end

%% Local helper functions (spectral fitting, MRD gridding, QC figures)
function [fitObj,source,isBonus] = selectGESpectralFit(MainInput,G)
% The EXACT MRD field AppendedDissolvedNMRFit stores the SELECTED spectral
% fit for all downstream analysis. Selection precedence:
%   1) explicitly supplied imaging-bonus fitted NMR object
%   2) explicitly supplied imaging-bonus post-dissolved raw FID (fit here)
%   3) separate GE calibration dissolved fit (analysis ONLY)
% The XIPline GE reader extracts waveform-validated appended FIDs. Never use calibration for contamination subtraction.
fitObj = [];
source = 'unavailable';
isBonus = false;

bonusFit = getOption(MainInput,'GE_BonusDissolvedNMRFit',[]);
bonusFID = getOption(MainInput,'GE_BonusPostDissolvedFID',[]);
if isempty(bonusFID)
    bonusFID = getOption(MainInput,'GE_BonusDissolvedFID',[]);
end
isAutoBonus = false;
if isempty(bonusFID) && isfield(G,'DissolvedBonusFID') && ...
        ~isempty(G.DissolvedBonusFID) && ...
        isfield(G,'BonusAcquisitionIndices') && ...
        numel(G.BonusAcquisitionIndices)==2
    % Fit the acquired samples, not the 512-point zero-filled display FID.
    if isfield(G,'DissolvedBonusFIDAcquired') && ...
            ~isempty(G.DissolvedBonusFIDAcquired)
        bonusFID = G.DissolvedBonusFIDAcquired;
    else
        bonusFID = G.DissolvedBonusFID;
    end
    isAutoBonus = true;
end

if ~isempty(bonusFit)
    validateGESpectralFit(bonusFit,'imaging bonus fit');
    fitObj = bonusFit;
    source = 'imaging bonus (supplied fitted spectrum)';
    isBonus = true;
elseif ~isempty(bonusFID)
    % The automatically extracted FID dwell is derived from the waveform
    % time axis. Manual FIDs still require an explicit dwell if not given.
    dwell = getOption(MainInput,'GE_BonusDwell_s',[]);
    if isempty(dwell) && isAutoBonus
        dwell = getOption(G,'BonusDwell_s',[]);
    end
    assert(isnumeric(dwell) && isscalar(dwell) && ...
        isfinite(dwell) && dwell>0, ...
        'A valid GE bonus FID dwell time in seconds is required.');
    try
        candidate = fitGEImagingBonusFID(bonusFID,dwell);
        validateGESpectralFit(candidate,'fitted imaging bonus FID');
        % Do not apply subtraction if the acquired complex FID is poorly
        % explained by the three-component spectral model.
        tt = double(candidate.t(:));
        measured = double(candidate.timeDomainSignal(:));
        fitted = sum(candidate.calcComponentTimeDomainSignal(tt),2);
        relError = norm(measured(:)-fitted(:))/max(norm(measured(:)),eps);
        maxRelError = getOption(MainInput,'GE_BonusMaxRelativeFitError',0.35);
        if ~isfinite(relError) || relError>maxRelError
            error('GE bonus 3-component fit residual %.3f > %.3f', ...
                relError,maxRelError);
        end
        fitObj = candidate;
        if isAutoBonus
            source = 'imaging bonus (auto-extracted and fitted)';
        else
            source = 'imaging bonus (user-supplied FID, fitted)';
        end
        isBonus = true;
        fprintf('Imaging bonus complex FID relative fit error: %.4f\n',relError);
    catch ME
        if ~isAutoBonus, rethrow(ME); end
        warning(['Auto-extracted bonus FID did not yield a validated fit. ' ...
            'Skipping gas subtraction; calibration fallback for analysis. %s'], ...
            ME.message);
    end
end
if isempty(fitObj)
    calibrationFit = getOption(G,'CalibrationDissolvedNMRFit',[]);
    if ~isempty(calibrationFit)
        validateGESpectralFit(calibrationFit,'separate GE calibration fit');
        fitObj = calibrationFit;
        source = 'separate GE calibration fallback';
    end
end
end

function validateGESpectralFit(obj,source)
% Validate data needed in spectroscopy, RBC keyholing and gas correction.
if ~isobject(obj) || ~isprop(obj,'area') || ...
        ~isprop(obj,'phase') || ~isprop(obj,'fwhm') || ...
        ~isprop(obj,'t') || ~isprop(obj,'f') || ...
        ~isprop(obj,'spectralDomainSignal') || ...
        ~ismethod(obj,'calcComponentTimeDomainSignal')
    error('%s must be a valid XIPline NMR fit object.',source);
end
A = double(obj.area(:)); P = double(obj.phase(:));
if numel(A)<3 || numel(P)<3 || ...
        ~all(isfinite(A(1:3))) || ~all(isfinite(P(1:3))) || ...
        any(A(1:3)<0) || ~any(A(1:3)>0)
    error('%s does not have valid RBC, barrier and gas fit parameters.',source);
end
end

function fitObj = fitGEImagingBonusFID(fid,dwell_s)
% Fit acquired post-imaging dissolved bonus spectrum using the same
% three-component Voigt model and constraints as the original MRD routine.
assert(isnumeric(fid) && isvector(fid) && numel(fid)>=32, ...
    'Imaging bonus dissolved FID must be a single complex vector of >=32 samples.');
fid = double(fid(:));
assert(all(isfinite(real(fid))) && all(isfinite(imag(fid))), ...
    'Imaging bonus dissolved FID contains non-finite samples.');
time = dwell_s*(0:numel(fid)-1)';
A0 = max(abs(fid(1)),eps);
area0 = [0.27*A0 A0 0.1*A0];
freq0 = [534 -126 -7084];
fwhm0 = [300 273 44];
fwhmG0 = [0 275 0];
phase0 = [-95 151 9];
fitObj = GasExchangeFunctions.GasExchange_Spectro.NMR_TimeFit_v( ...
    fid,time,area0,freq0,fwhm0,fwhmG0,phase0,[],[]);
fitObj.fitTimeDomainSignal();
fitObj.setBounds( ...
    [0 0 0],1E10*[1 1 1], ...
    [500 -2000 -12000],[2000 0 -4000], ...
    [0 0 0],[Inf Inf Inf], ...
    [0 0 0],[0 Inf 0], ...
    [-Inf -Inf -Inf],[Inf Inf Inf]);
fitObj.fitTimeDomainSignal();
end

