%% ------------------------------------------------------------------------
% LOCAL STEP 1: native GE images, raw k-space, bonus FIDs and calibration
%% ------------------------------------------------------------------------
function G = runNativeGE(In)
% The helper is local: no second high-level reconstruction file is needed.
% Gas subtraction is intentionally deferred until the bonus FID is fitted.

%% 1A. Find the ScanArchive, header, waveform and reconstruction settings
p = findGEFiles(In.XeFullPath);
fprintf('ScanArchive: %s\nWaveform: %s\n',p.data,p.waveform);

%% 1B. Native GE reconstruction + XIPline extraction
[bb,bbabs,gx] = LoadData.GE_Recon.CPIR_Scripts.CPIR_GERecon. ...
    recon_grid3d_gx_XIPline(p.data,p.header,p.waveform, ...
    p.mtx_reco,p.interp_factor,p.delay,p.lb,[], ...
    p.mask_fac,p.coco,p.plt,p.grdwrp);

%% 1C. Identify gas and dissolved image streams
assert(size(bbabs,4)==2,'Expected two GE gas-exchange image streams.');
imageStrength = [sum(abs(bbabs(:,:,:,1)),'all'), ...
                 sum(abs(bbabs(:,:,:,2)),'all')];
[~,gasStream] = max(imageStrength);
disStream = 3-gasStream;
G = struct();
G.GasStreamIndex = gasStream;
G.DissolvedStreamIndex = disStream;
G.StreamSignal = imageStrength;
G.GasImage = orientGXVolume(squeeze(bb(:,:,:,gasStream,:)));
G.DissolvedImage = orientGXVolume(squeeze(bb(:,:,:,disStream,:)));
G.GasImageCombined = double(abs(orientGXVolume(squeeze(bbabs(:,:,:,gasStream)))));
G.DissolvedImageCombined = double(abs(orientGXVolume(squeeze(bbabs(:,:,:,disStream)))));
G.UncorrectedVentImage = G.GasImage;
G.ImageComplex = bb;

%% 1D. Ventilation bias correction (same algorithm as original)
try
    gas = G.GasImage;
    mask = abs(gas) > prctile(abs(gas(:)),95)/3;
    mask = imerode(mask,strel('sphere',5));
    regions = sortrows(regionprops3(mask,'all'),1,'descend');
    mask2 = false(size(mask));
    if ~isempty(regions)
