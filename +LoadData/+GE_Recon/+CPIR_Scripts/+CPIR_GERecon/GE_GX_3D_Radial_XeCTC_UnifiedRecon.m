function [gas,dis,corrdis] = lowResThreeStreams(N,gasData,disData,corrData,traj,kw,extent)
% Share the expensive sparse system and iterative density compensation
% across all three contrast streams (identical sampling geometry).
% Same Gaussian gridding method, DCF and output convention as original
% MRD Dissolved_LowResImageRecon.m. Configurable sigma/extent; NO extra
% k-space filter or frequency-domain apodization is applied to the data.
oversamp = 3; dcfIter = 15;
Npts = numel(gasData);
assert(isequal(size(gasData),size(disData),size(corrData)) && ...
       size(traj,1)==3 && numel(traj)/3==Npts, ...
       'Mismatch in shared LR reconstruction inputs.');
traj2 = reshape(permute(traj,[2 3 1]),[],3);
assert(size(traj2,1)==Npts,'Trajectory reshape mismatch.');
% Exact same ordering as lowRes recon's [reshape(traj(1,:,:)) ...]
% and column-major reshape(data,[],1).

kernelObj = GasExchangeFunctions.GasExchange_Recon.SysModel.Kernel.Gaussian(kw,extent,true);
proxObj = GasExchangeFunctions.GasExchange_Recon.SysModel.Proximity.L2Proximity(kernelObj,true);
systemObj = GasExchangeFunctions.GasExchange_Recon.SysModel.MatrixSystemModel( ...
    traj2,oversamp,[N N N],proxObj,true);
clear kernelObj proxObj;
dcfObj = GasExchangeFunctions.GasExchange_Recon.DCF.Iterative(systemObj,dcfIter,true);
reconObj = GasExchangeFunctions.GasExchange_Recon.ReconModel.LSQGridded( ...
    systemObj,dcfObj,true);
reconObj.PixelShift=[0 0 0];
reconObj.crop=true;
reconObj.deapodize=true;
clear dcfObj;

gas=rot90(flip(reconObj.reconstruct(gasData(:),traj2)));
dis=rot90(flip(reconObj.reconstruct(disData(:),traj2)));
corrdis=rot90(flip(reconObj.reconstruct(corrData(:),traj2)));
end

function v = resizeComplex3D(v,n)
if size(v,1)==n, return; end
r=imresize3(real(v),[n n n],'linear');
i=imresize3(imag(v),[n n n],'linear');
v=complex(r,i);
end

function v = applyOrientation(v,i)
assert(i>=1 && i<=16 && i==round(i),'Orientation must be 1..16.');
% 4 rotations x 2 mirror states x 2 z-reversal states
rot = mod(i-1,4);
mirror = mod(floor((i-1)/4),2);
flipZ = floor((i-1)/8);
v=rot90(v,rot);
if mirror, v=flip(v,1); end
if flipZ, v=flip(v,3); end
end

function [bestIdx,bestScore] = findLRDihedralOrientation(LR,Native)
% 16 discrete tests in the same voxel frame, selected by normalized
% correlation. It does NOT estimate translation, deformation or FOV.
N=size(Native,1);
if size(LR,1)~=N, error('LR/native sizes differ during orientation QC.'); end
% Work on coarse versions to reduce processing and strip fine artifacts.
M=min(48,N);
ref=imresize3(double(Native),[M M M],'linear');
mov=imresize3(double(LR),[M M M],'linear');
ref=ref-mean(ref(:));
rn=norm(ref(:));
bestScore=-Inf; bestIdx=1;
for ii=1:16
    cand=applyOrientation(mov,ii);
    cand=cand-mean(cand(:));
    score=dot(ref(:),cand(:))/(rn*norm(cand(:))+eps);
    if score>bestScore
        bestScore=score;
        bestIdx=ii;
    end
end
if bestScore<0.5
    warning('Weak LR-to-GE orientation correlation %.3f; inspect anatomy manually.',bestScore);
end
end

